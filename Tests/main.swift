import AppKit

assert(movedSelection(0, count: 0, direction: 1) == 0)
assert(movedSelection(0, count: 3, direction: -1) == 0)
assert(movedSelection(0, count: 3, direction: 1) == 1)
assert(movedSelection(2, count: 3, direction: 1) == 2)
assert(!hasKeyboardShortcutModifiers([.numericPad, .function]))
assert(hasKeyboardShortcutModifiers([.shift, .numericPad]))

var history = History(limit: 2)
history.add(.text("first"))
history.add(.text("second"))
history.add(.text("first"))
history.add(.text("  \n"))
assert(history.items == [.text("first"), .text("second")])
history.add(.text("third"))
assert(history.items == [.text("third"), .text("first")])
history.clear()
assert(history.items.isEmpty)
var duplicates = History(items: [.text("é\r\nline"), .text("e\u{301}\nline"), .text("other")], pinned: [.text("e\u{301}\nline")])
assert(duplicates.items == [.text("e\u{301}\nline"), .text("other")])
assert(duplicates.pinned == [.text("e\u{301}\nline")])
duplicates.add(.text("é\nline"))
assert(duplicates.items.count == 2)
duplicates.recordUse(.text("other"))
duplicates.recordUse(.text("other"))
duplicates.recordUse(.text("e\u{301}\nline"))
assert(duplicates.frequent == [.text("e\u{301}\nline"), .text("other")])
assert(duplicates.items == [.text("e\u{301}\nline"), .text("other")])
duplicates.clear()
assert(duplicates.count(for: .text("other")) == 0)
assert(duplicates.count(for: .text("é\nline")) == 1)
history.add(.text("kept"))
history.togglePin(.text("kept"))
history.add(.text("a"))
history.add(.text("b"))
history.add(.text("c"))
assert(history.items == [.text("kept"), .text("c"), .text("b")])
history.clear()
assert(history.items == [.text("kept")])
history.togglePin(.text("kept"))
history.clear()
assert(history.items.isEmpty)

@MainActor func requireSaved(_ store: ClipboardStore) async {
    let saved = await store.flush()
    assert(saved, store.storageStatus ?? "history was not saved")
}

@MainActor func runChecks() async {
    let board = NSPasteboard(name: NSPasteboard.Name("ClipHarborTests-\(UUID().uuidString)"))
    let suite = "ClipHarborTests-\(UUID().uuidString)"
    let defaults = UserDefaults(suiteName: suite)!
    let directory = FileManager.default.temporaryDirectory.appendingPathComponent(suite)
    let file = directory.appendingPathComponent("history.plist")
    defer {
        board.releaseGlobally()
        defaults.removePersistentDomain(forName: suite)
        try? FileManager.default.removeItem(at: directory)
    }
    defaults.set(["旧记录"], forKey: "clipboardHistory")
    let store = ClipboardStore(pasteboard: board, defaults: defaults, file: file)
    assert(store.history.items == [.text("旧记录")])
    board.clearContents()
    board.setString("测试内容 Alpha", forType: .string)
    try! await Task.sleep(nanoseconds: 1_200_000_000)
    assert(store.history.items.first == .text("测试内容 Alpha"), "timer did not record clipboard")
    let bitmap = NSBitmapImageRep(bitmapDataPlanes: nil, pixelsWide: 2, pixelsHigh: 2, bitsPerSample: 8, samplesPerPixel: 4, hasAlpha: true, isPlanar: false, colorSpaceName: .deviceRGB, bytesPerRow: 0, bitsPerPixel: 0)!
    let png = bitmap.representation(using: .png, properties: [:])!
    let sourceDir = directory.appendingPathComponent("source")
    try! FileManager.default.createDirectory(at: sourceDir, withIntermediateDirectories: true)
    try! png.write(to: sourceDir.appendingPathComponent("微信图片_1.dat"))
    try! Data("encrypted".utf8).write(to: sourceDir.appendingPathComponent("微信图片_2.dat"))
    let nested = sourceDir.appendingPathComponent("nested")
    try! FileManager.default.createDirectory(at: nested, withIntermediateDirectories: true)
    try! png.write(to: sourceDir.appendingPathComponent("重复.dat"))
    try! png.write(to: nested.appendingPathComponent("重复.dat"))
    let chat = "开头\n小王\n2026年10月31日 18:32\n第一行\n第二行\n\n小李\n2026年10月31日 18:33\n[图片] 微信图片_1.dat\n[图片] 微信图片_2.dat\n[图片] 重复.dat\n[图片] 不存在.dat"
    let parsed = WeChatExport.parse(chat)
    assert(parsed.messages.count == 2 && parsed.messages[0].content.contains("第二行"))
    let export = try! WeChatExport.export(text: chat, source: sourceDir, destination: directory)
    assert(export.messages == 2 && export.matched == 1 && export.unmatched == 3)
    let outputText = try! String(contentsOf: export.directory.appendingPathComponent("conversation.md"), encoding: .utf8)
    assert(outputText.contains("![图片](images/image-001.png)"))
    assert(outputText.contains("微信图片_2.dat") && outputText.contains("多个同名") && outputText.contains("不存在.dat"))
    assert(FileManager.default.fileExists(atPath: export.directory.appendingPathComponent("images/image-001.png").path))
    let fallback = try! WeChatExport.export(text: "没有可识别头部\n[图片] 不存在.dat", source: nil, destination: directory)
    assert(fallback.messages == 0 && fallback.unmatched == 1)
    let fallbackText = try! String(contentsOf: fallback.directory.appendingPathComponent("conversation.md"), encoding: .utf8)
    assert(fallbackText.contains("没有可识别头部"))
    let linkedImage = sourceDir.appendingPathComponent("unrelated-name.png")
    try! png.write(to: linkedImage)
    let directChat = "小王\n2026年10月31日 18:32\n[图片] 聊天图片.dat"
    let metadata = try! JSONSerialization.data(withJSONObject: [["text": directChat, "file": linkedImage.path]])
    let directResult = try! WeChatExport.export(text: directChat, source: sourceDir, destination: directory, clipboardMetadata: metadata)
    assert(directResult.matched == 1 && directResult.unmatched == 0)
    let directOutput = try! String(contentsOf: directResult.directory.appendingPathComponent("conversation.md"), encoding: .utf8)
    assert(directOutput.contains("按微信多选数据中的同一消息关联"))
    let ambiguousMetadata = try! JSONSerialization.data(withJSONObject: [["text": directChat, "file": linkedImage.path], ["text": directChat, "file": linkedImage.path]])
    let ambiguous = try! WeChatExport.export(text: directChat, source: sourceDir, destination: directory, clipboardMetadata: ambiguousMetadata)
    assert(ambiguous.matched == 0 && ambiguous.unmatched == 1)
    let invalidMetadata = try! JSONSerialization.data(withJSONObject: [["text": directChat, "file": "/tmp/unrelated-name.png"]])
    let invalid = try! WeChatExport.export(text: directChat, source: sourceDir, destination: directory, clipboardMetadata: invalidMetadata)
    assert(invalid.matched == 0 && invalid.unmatched == 1)
    assert(WeChatExport.parse("名字\n2026年10月31日 18:32\n2026年10月31日 18:33").messages.count == 1)
    board.clearContents()
    board.setData(png, forType: .png)
    try! await Task.sleep(nanoseconds: 1_200_000_000)
    assert(store.history.items.first == .image(png), "timer did not record image")
    let order = store.history.items
    store.copy(.text("测试内容 Alpha"))
    assert(board.string(forType: .string) == "测试内容 Alpha")
    assert(store.history.items == order)
    assert(store.history.count(for: .text("测试内容 Alpha")) == 0)
    store.poll()
    assert(store.history.items == order)
    store.copy(.image(png))
    assert(board.data(forType: .png) == png)
    assert(board.data(forType: .tiff) != nil)
    await requireSaved(store)
    let restored = ClipboardStore(pasteboard: board, defaults: defaults, file: file, monitor: false)
    assert(restored.history.items == store.history.items)
    assert(defaults.stringArray(forKey: "clipboardHistory") == nil)
    board.clearContents()
    let files = [URL(fileURLWithPath: "/tmp/first.txt"), URL(fileURLWithPath: "/tmp/second.txt")]
    board.writeObjects(files as [NSURL])
    store.poll()
    guard case .files(let paths) = store.history.items.first else { fatalError("files not captured") }
    assert(paths.count == 2)
    let fileClip = Clip.files(paths)
    store.togglePin(fileClip)
    assert(store.copy(fileClip))
    assert((board.readObjects(forClasses: [NSURL.self]) as? [URL])?.count == 2)
    board.clearContents()
    let richItem = NSPasteboardItem()
    richItem.setString("聊天记录", forType: .string)
    richItem.setData(Data("{\\rtf1 test}".utf8), forType: .rtf)
    board.writeObjects([richItem])
    store.poll()
    guard case .rich(let parts) = store.history.items[1] else { fatalError("rich text not captured") }
    assert(store.copy(.rich(parts)))
    assert(board.string(forType: .string) == "聊天记录")
    assert(board.data(forType: .rtf) != nil)
    await requireSaved(store)
    let pinnedRestored = ClipboardStore(pasteboard: board, defaults: defaults, file: file, monitor: false)
    assert(pinnedRestored.history.pinned == [fileClip])
    store.recordUse(fileClip)
    store.recordUse(fileClip)
    await requireSaved(store)
    let usageRestored = ClipboardStore(pasteboard: board, defaults: defaults, file: file, monitor: false)
    assert(usageRestored.history.count(for: fileClip) == 2)
    board.clearContents()
    let item = NSPasteboardItem()
    item.setString("secret", forType: .string)
    item.setString("", forType: NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"))
    board.writeObjects([item])
    store.poll()
    assert(!store.history.items.contains(.text("secret")))
    store.clear()
    await requireSaved(store)
    let cleared = ClipboardStore(pasteboard: board, defaults: defaults, file: file, monitor: false)
    assert(cleared.history.items == [fileClip])
    assert(cleared.history.pinned == [fileClip])
    assert(cleared.history.count(for: fileClip) == 2)
    let legacyFile = directory.appendingPathComponent("legacy.plist")
    try! PropertyListEncoder().encode([Clip.text("旧版历史")]).write(to: legacyFile)
    let legacy = ClipboardStore(pasteboard: board, defaults: defaults, file: legacyFile, monitor: false)
    assert(legacy.history.items == [.text("旧版历史")])
    print("History, timer, files, rich text, images, pins, migration, persistence and clear checks passed")
    store.prepareToTerminate()
    await runStorageChecks()
    await runInteractionChecks()
    try! runWeChatChecks()
}

Task { @MainActor in
    await runChecks()
    exit(0)
}
RunLoop.main.run()
