@MainActor
final class ClipboardStore: ObservableObject {
    @Published private(set) var history: History
    @Published var error: String?
    @Published private(set) var isPaused: Bool
    @Published private(set) var storageStatus: String?
    @Published private(set) var needsRecovery = false
    private let pasteboard: NSPasteboard
    private let defaults: UserDefaults
    private let file: URL
    private let historyFile: HistoryFile
    private let monitorsClipboard: Bool
    private var changeCount: Int
    private var timer: Timer?
    private var saveTask: Task<Void, Never>?
    private var revision = 0
    private var savedRevision = -1
    private var recovering = false
    private var terminating = false
    private let key = "clipboardHistory"
    private let sensitiveTypes = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
    ]

    init(pasteboard: NSPasteboard = .general, defaults: UserDefaults = .standard,
         file: URL = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
            .appendingPathComponent("ClipHarbor/history.plist"), monitor: Bool = true) {
        self.pasteboard = pasteboard
        self.defaults = defaults
        self.file = file
        self.historyFile = HistoryFile(file: file)
        self.monitorsClipboard = monitor
        self.isPaused = defaults.bool(forKey: "recordingPaused")
        if FileManager.default.fileExists(atPath: file.path) {
            do {
                let data = try Data(contentsOf: file)
                if let archive = try? PropertyListDecoder().decode(Archive.self, from: data) {
                    history = History(items: archive.items, pinned: archive.pinned, usage: archive.usage ?? [])
                } else {
                    history = History(items: try PropertyListDecoder().decode([Clip].self, from: data))
                }
            } catch {
                history = History()
                needsRecovery = true
                storageStatus = "历史保存已暂停：原文件无法读取。请备份并恢复后继续保存。"
                self.error = "无法读取历史记录：\(error.localizedDescription)"
            }
        } else {
            history = History(items: (defaults.stringArray(forKey: key) ?? []).map(Clip.text))
        }
        changeCount = pasteboard.changeCount
        do { try HistoryFile.protect(file) }
        catch {
            storageStatus = "无法保护历史文件权限：\(error.localizedDescription)"
            self.error = storageStatus
        }
        startMonitoring()
    }

    private func startMonitoring() {
        guard monitorsClipboard else { return }
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            Task { @MainActor in self?.poll() }
        }
    }

    func poll() {
        guard !terminating else { return }
        guard pasteboard.changeCount != changeCount else { return }
        changeCount = pasteboard.changeCount
        guard !isPaused else { return }
        guard pasteboard.availableType(from: sensitiveTypes) == nil else { return }
        let boardItems = pasteboard.pasteboardItems ?? []
        let files = boardItems.compactMap { $0.string(forType: .fileURL) }
        if files.count == boardItems.count, !files.isEmpty {
            add(.files(files))
        } else if boardItems.count > 1 || boardItems.contains(where: { $0.types.contains(.rtf) || $0.types.contains(.rtfd) || $0.types.contains(.html) }) {
            let allowed: Set<NSPasteboard.PasteboardType> = [.string, .rtf, .rtfd, .html, .png, .tiff, .fileURL]
            let representations = boardItems.map { item in
                Dictionary(uniqueKeysWithValues: item.types.filter { allowed.contains($0) }.compactMap { type in
                    item.data(forType: type).map { (type.rawValue, $0) }
                })
            }.filter { !$0.isEmpty }
            if !representations.isEmpty { add(.rich(representations)) }
        } else if let data = pasteboard.data(forType: .png), NSImage(data: data) != nil {
            add(.image(data))
        } else if let data = pasteboard.data(forType: .tiff),
                  let image = NSBitmapImageRep(data: data),
                  let png = image.representation(using: .png, properties: [:]) {
            add(.image(png))
        } else if let text = pasteboard.string(forType: .string) {
            add(.text(text))
        }
    }

    @discardableResult func copy(_ item: Clip) -> Bool {
        pasteboard.clearContents()
        let copied: Bool
        switch item {
        case .text(let text): copied = pasteboard.setString(text, forType: .string)
        case .files(let paths):
            let urls = paths.compactMap(URL.init(string:))
            copied = urls.count == paths.count && pasteboard.writeObjects(urls as [NSURL])
        case .rich(let representations):
            let objects = representations.map { values in
                let item = NSPasteboardItem()
                for (type, data) in values { item.setData(data, forType: NSPasteboard.PasteboardType(type)) }
                return item
            }
            copied = pasteboard.writeObjects(objects)
        case .image(let data):
            copied = pasteboard.setData(data, forType: .png)
            if let tiff = NSImage(data: data)?.tiffRepresentation {
                pasteboard.setData(tiff, forType: .tiff)
            }
        }
        changeCount = pasteboard.changeCount
        if !copied { error = "无法复制到剪贴板" }
        return copied
    }

    func clear() {
        history.clear()
        save()
    }

    func delete(_ item: Clip) {
        history.delete(item)
        save()
    }

    func setPaused(_ paused: Bool) {
        isPaused = paused
        defaults.set(paused, forKey: "recordingPaused")
        changeCount = pasteboard.changeCount
    }

    var clipboardVersion: Int { pasteboard.changeCount }

    func isCurrentClipboard(_ version: Int) -> Bool {
        pasteboard.changeCount == version
    }

    func prepareToTerminate() {
        terminating = true
        timer?.invalidate()
        timer = nil
    }

    func cancelTermination() {
        terminating = false
        startMonitoring()
    }

    func recordUse(_ item: Clip) {
        history.recordUse(item)
        save()
    }

    func togglePin(_ item: Clip) {
        history.togglePin(item)
        save()
    }

    private func add(_ item: Clip) {
        var updated = history
        guard updated.add(item) else { return }
        history = updated
        save()
    }

    private func save() {
        revision += 1
        guard !needsRecovery else { return }
        saveTask?.cancel()
        saveTask = Task { [weak self] in
            do { try await Task.sleep(nanoseconds: 150_000_000) }
            catch { return }
            _ = await self?.persistLatest()
        }
    }

    private var archive: Archive {
        Archive(items: history.items, pinned: history.pinned, usage: history.usage)
    }

    @discardableResult private func persistLatest() async -> Bool {
        guard !needsRecovery else { return false }
        let snapshotRevision = revision
        guard snapshotRevision > savedRevision else { return true }
        do {
            try await historyFile.save(archive, revision: snapshotRevision)
            savedRevision = max(savedRevision, snapshotRevision)
            defaults.removeObject(forKey: key)
            if revision == snapshotRevision { storageStatus = nil }
            return true
        } catch is CancellationError {
            return false
        } catch {
            if revision == snapshotRevision {
                storageStatus = "历史尚未保存：\(error.localizedDescription)"
                self.error = storageStatus
            }
            return false
        }
    }

    func retrySave() { save() }

    func flush() async -> Bool {
        saveTask?.cancel()
        guard !needsRecovery, !recovering else { return false }
        repeat {
            let snapshotRevision = revision
            guard await persistLatest() else { return false }
            if snapshotRevision == revision { return true }
        } while true
    }

    func recoverHistory() {
        guard needsRecovery, !recovering else { return }
        recovering = true
        storageStatus = "正在备份原历史并恢复保存…"
        let snapshot = archive
        let snapshotRevision = revision
        Task {
            do {
                let backup = try await historyFile.recover(snapshot, revision: snapshotRevision)
                needsRecovery = false
                recovering = false
                savedRevision = max(savedRevision, snapshotRevision)
                defaults.removeObject(forKey: key)
                if await flush() {
                    storageStatus = nil
                    error = backup.map { "已恢复保存。原历史备份：\($0.path)" }
                }
            } catch {
                recovering = false
                storageStatus = "恢复失败，历史保存仍暂停：\(error.localizedDescription)"
                self.error = storageStatus
            }
        }
    }
}

func plainTextFromHTML(_ html: String) -> String {
    // Use local text conversion only: AppKit's HTML importer can load remote resources.
    var text = html.replacingOccurrences(of: "(?s)<!--.*?(?:-->|$)", with: "", options: .regularExpression)
    text = text.replacingOccurrences(of: "(?is)<(script|style|head)\\b[^>]*>.*?(?:</\\1\\s*>|$)", with: "", options: .regularExpression)
    let source = text as NSString
    let pre = try! NSRegularExpression(pattern: "(?is)<pre\\b(?:\"[^\"]*\"|'[^']*'|[^'\">])*>(.*?)(?:</pre\\s*>|$)")
    var sections: [String] = []
    var offset = 0
    for match in pre.matches(in: text, range: NSRange(location: 0, length: source.length)) {
        let normal = htmlFragmentText(source.substring(with: NSRange(location: offset, length: match.range.location - offset)))
        if !normal.isEmpty { sections.append(normal) }
        sections.append(htmlFragmentText(source.substring(with: match.range(at: 1)), preservingWhitespace: true))
        offset = NSMaxRange(match.range)
    }
    let trailing = htmlFragmentText(source.substring(from: offset))
    if !trailing.isEmpty { sections.append(trailing) }
    var result = ""
    for section in sections {
        if !result.isEmpty, !result.hasSuffix("\n"), !section.hasPrefix("\n") { result += "\n" }
        result += section
    }
    return result
}

private func htmlFragmentText(_ html: String, preservingWhitespace: Bool = false) -> String {
    var text = preservingWhitespace ? html : html.replacingOccurrences(of: "[ \\t\\r\\f]+", with: " ", options: .regularExpression)
    text = text.replacingOccurrences(of: "(?i)<(?:br|/?(?:p|div|li|tr|h[1-6]|blockquote))\\b(?:\"[^\"]*\"|'[^']*'|[^'\">])*>", with: "\n", options: .regularExpression)
    text = text.replacingOccurrences(of: "(?i)</(?:td|th)\\s*>", with: "\t", options: .regularExpression)
    text = text.replacingOccurrences(of: "(?s)<(?:/?[A-Za-z][A-Za-z0-9:-]*|![A-Za-z]+|\\?xml\\b)(?:\"[^\"]*\"|'[^']*'|[^'\"<>])*>", with: "", options: .regularExpression)
    // shortcut: uncommon HTML named entities stay literal; extend the map if real sources require them.
    let entities = ["nbsp": " ", "copy": "©", "reg": "®", "trade": "™", "hellip": "…", "ndash": "–", "mdash": "—", "bull": "•", "lsquo": "‘", "rsquo": "’", "ldquo": "“", "rdquo": "”", "euro": "€", "pound": "£", "yen": "¥"]
    text = CFXMLCreateStringByUnescapingEntities(nil, text as CFString, entities as CFDictionary) as String? ?? text
    if preservingWhitespace { return text }
    return text.replacingOccurrences(of: " +", with: " ", options: .regularExpression)
        .replacingOccurrences(of: "[ \\t]*\\n[ \\t]*", with: "\n", options: .regularExpression)
        .replacingOccurrences(of: "\\n{2,}", with: "\n", options: .regularExpression)
        .trimmingCharacters(in: .whitespacesAndNewlines)
}

extension Clip {
    var plainText: String? {
        switch self {
        case .text(let text): return text
        case .files(let paths): return paths.map { URL(string: $0)?.path ?? $0 }.joined(separator: "\n")
        case .image: return nil
        case .rich(let parts):
            let texts = parts.compactMap { part -> String? in
                if let data = part[NSPasteboard.PasteboardType.string.rawValue], let text = String(data: data, encoding: .utf8), !text.isEmpty { return text }
                if let data = part[NSPasteboard.PasteboardType.fileURL.rawValue], let path = String(data: data, encoding: .utf8) { return URL(string: path)?.path ?? path }
                if let data = part[NSPasteboard.PasteboardType.rtf.rawValue], let text = NSAttributedString(rtf: data, documentAttributes: nil)?.string, !text.isEmpty { return text }
                if let data = part[NSPasteboard.PasteboardType.rtfd.rawValue], let text = NSAttributedString(rtfd: data, documentAttributes: nil)?.string, !text.isEmpty { return text }
                if let data = part[NSPasteboard.PasteboardType.html.rawValue], let html = String(data: data, encoding: .utf8) ?? String(data: data, encoding: .utf16) {
                    let text = plainTextFromHTML(html)
                    return text.isEmpty ? nil : text
                }
                return nil
            }
            return texts.isEmpty ? nil : texts.joined(separator: "\n")
        }
    }

    var imageData: [Data] {
        switch self {
        case .image(let data): return [data]
        case .rich(let parts): return parts.compactMap { $0[NSPasteboard.PasteboardType.png.rawValue] ?? $0[NSPasteboard.PasteboardType.tiff.rawValue] }
        default: return []
        }
    }

    var previewLabel: String {
        previewLabel(plainText: plainText)
    }

    func previewLabel(plainText text: String?) -> String {
        if let text, !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty { return text }
        let count = imageData.count
        return count > 0 ? (count == 1 ? "图片" : "\(count) 张图片") : "富文本内容"
    }
}

struct ClipTextPresentation {
    let plainText: String?
    let label: String
}

@MainActor
final class ClipTextCache: ObservableObject {
    private var values: [Clip: ClipTextPresentation] = [:]
    private var historyKeys: Set<Clip> = []
    private var subscription: AnyCancellable?
    private let extract: (Clip) -> String?

    init(store: ClipboardStore, extract: @escaping (Clip) -> String? = { $0.plainText }) {
        self.extract = extract
        subscription = store.$history.sink { [weak self] history in
            guard let self else { return }
            self.historyKeys = Set(history.items)
            self.values = self.values.filter { self.historyKeys.contains($0.key) }
        }
    }

    var cachedCount: Int { values.count }

    func presentation(for item: Clip) -> ClipTextPresentation {
        if let value = values[item] { return value }
        let text = extract(item)
        let value = ClipTextPresentation(plainText: text, label: item.previewLabel(plainText: text))
        // A view can finish evaluating a removed row before its next update.
        if historyKeys.contains(item) { values[item] = value }
        return value
    }
}

func movedSelection(_ index: Int, count: Int, direction: Int) -> Int {
    guard count > 0 else { return 0 }
    return min(max(index + direction, 0), count - 1)
}

func hasKeyboardShortcutModifiers(_ flags: NSEvent.ModifierFlags) -> Bool {
    !flags.intersection([.command, .control, .option, .shift]).isEmpty
}

func historyNavigationKey(_ event: NSEvent, editor: NSTextView) -> UInt16? {
    guard !editor.hasMarkedText(), !hasKeyboardShortcutModifiers(event.modifierFlags),
          [36, 76, 125, 126].contains(event.keyCode) else { return nil }
    return event.keyCode
}

private struct HistoryKeys: NSViewRepresentable {
    var handle: (UInt16) -> Bool

    final class Coordinator {
        var handle: (UInt16) -> Bool = { _ in false }
        var monitor: Any?
        deinit { if let monitor { NSEvent.removeMonitor(monitor) } }
    }

    func makeCoordinator() -> Coordinator { Coordinator() }
    func makeNSView(context: Context) -> NSView {
        let view = NSView()
        let coordinator = context.coordinator
        coordinator.monitor = NSEvent.addLocalMonitorForEvents(matching: .keyDown) { [weak view, weak coordinator] event in
            guard let view, let window = view.window, event.window === window,
                  let editor = window.firstResponder as? NSTextView,
                  let key = historyNavigationKey(event, editor: editor), let coordinator else { return event }
            return coordinator.handle(key) ? nil : event
        }
        return view
    }
    func updateNSView(_ view: NSView, context: Context) { context.coordinator.handle = handle }
}

enum HarborStyle {
    static let accent = Color(nsColor: NSColor(name: nil) { appearance in
        appearance.bestMatch(from: [.aqua, .darkAqua]) == .darkAqua
            ? NSColor(red: 0.39, green: 0.83, blue: 0.77, alpha: 1)
            : NSColor(red: 0.03, green: 0.46, blue: 0.43, alpha: 1)
    })
    static let canvas = Color(nsColor: NSColor(name: nil) { appearance in
        appearance.bestMatch(from: [.aqua, .darkAqua]) == .darkAqua
            ? NSColor(red: 0.12, green: 0.14, blue: 0.15, alpha: 1)
            : NSColor(red: 0.95, green: 0.96, blue: 0.96, alpha: 1)
    })
    static let surface = Color(nsColor: .controlBackgroundColor)
}

struct HistoryView: View {
    @ObservedObject var store: ClipboardStore
    @StateObject private var textCache: ClipTextCache
    var convert: () -> Void = {}
    var select: (Clip, Bool) -> Void
    @State private var search = ""
    @State private var showFrequent = false
    @State private var selectedIndex = 0
    @State private var keyboardNavigation = false
    @State private var previewItem: Clip?
    @State private var confirmingClear = false
    @FocusState private var searchFocused: Bool
    @State private var loginStatus = SMAppService.mainApp.status
    @AppStorage("shortcut") private var shortcut = "optionShiftV"

    init(store: ClipboardStore, convert: @escaping () -> Void = {}, select: @escaping (Clip, Bool) -> Void) {
        self.store = store
        self.convert = convert
        self.select = select
        _textCache = StateObject(wrappedValue: ClipTextCache(store: store))
    }

    private var items: [Clip] {
        let source = showFrequent ? store.history.frequent : store.history.items
        guard !search.isEmpty else { return source }
        return source.filter { textCache.presentation(for: $0).label.localizedCaseInsensitiveContains(search) }
    }

    var body: some View {
        Group {
            if let item = previewItem {
                ClipPreview(item: item, text: textCache.presentation(for: item).plainText, close: { previewItem = nil; searchFocused = true }, select: { plainText in
                    previewItem = nil
                    select(item, plainText)
                })
            } else {
                VStack(spacing: 0) {
                    header
                    if let status = store.storageStatus {
                        HStack(alignment: .top, spacing: 8) {
                            Image(systemName: "exclamationmark.triangle.fill").foregroundStyle(.orange)
                            Text(status).font(.caption).fixedSize(horizontal: false, vertical: true)
                            Spacer(minLength: 0)
                            Button(store.needsRecovery ? "备份并恢复" : "重试保存") {
                                if store.needsRecovery { store.recoverHistory() } else { store.retrySave() }
                            }.controlSize(.small)
                        }
                        .padding(10).background(Color.orange.opacity(0.10), in: RoundedRectangle(cornerRadius: 8))
                        .padding(.horizontal, 18).padding(.bottom, 12)
                    }
                    HStack(spacing: 9) {
                        Image(systemName: "magnifyingglass").foregroundStyle(.secondary)
                        TextField("搜索剪贴板", text: $search)
                            .textFieldStyle(.plain).focused($searchFocused)
                        if !search.isEmpty {
                            Button { search = ""; searchFocused = true } label: {
                                Image(systemName: "xmark.circle.fill").foregroundStyle(.secondary)
                            }.buttonStyle(.plain).accessibilityLabel("清除搜索")
                        }
                    }
                    .font(.system(size: 14)).padding(.horizontal, 12).padding(.vertical, 11)
                    .background(HarborStyle.surface, in: RoundedRectangle(cornerRadius: 10))
                    .overlay(RoundedRectangle(cornerRadius: 10).strokeBorder(searchFocused ? HarborStyle.accent.opacity(0.65) : Color.primary.opacity(0.10), lineWidth: 1))
                    .padding(.horizontal, 18)
                    HStack {
                        Picker("历史视图", selection: $showFrequent) {
                            Text("全部").tag(false)
                            Text("常用").tag(true)
                        }.pickerStyle(.segmented).labelsHidden().frame(width: 152, alignment: .leading)
                        Spacer()
                        Text("\(items.count) 条记录").font(.system(size: 11)).foregroundStyle(.secondary)
                    }.padding(.horizontal, 18).padding(.vertical, 12)
                    if items.isEmpty {
                        VStack(spacing: 10) {
                            Image(systemName: search.isEmpty ? "doc.on.clipboard" : "magnifyingglass")
                                .font(.system(size: 30, weight: .light)).foregroundStyle(HarborStyle.accent.opacity(0.7))
                            Text(!search.isEmpty ? "没有匹配的记录" : (showFrequent ? "暂无常用记录" : "暂无剪贴板记录"))
                                .font(.system(size: 14, weight: .medium))
                            Text(!search.isEmpty ? "换个关键词试试" : (showFrequent ? "通过这里粘贴后，常用内容会出现在此处" : (store.isPaused ? "继续记录后，复制的内容会出现在这里" : "复制一段文字或一张图片，从这里轻松找回")))
                                .font(.system(size: 12)).foregroundStyle(.secondary)
                        }.frame(maxWidth: .infinity, maxHeight: .infinity)
                    } else {
                        ScrollViewReader { proxy in
                            ScrollView {
                                LazyVStack(spacing: 4) {
                                    ForEach(Array(items.enumerated()), id: \.element) { index, item in
                                        historyRow(item, index: index).id(item)
                                    }
                                }.padding(.horizontal, 10).padding(.bottom, 10)
                            }
                            .onChange(of: selectedIndex) { index in
                                if keyboardNavigation, items.indices.contains(index) { proxy.scrollTo(items[index], anchor: .center) }
                            }
                        }
                    }
                    footer
                }
            }
        }
        .frame(width: 460, height: 600)
        .background(HarborStyle.canvas).tint(HarborStyle.accent)
        .background(HistoryKeys { key in
            guard previewItem == nil, !confirmingClear else { return false }
            switch key {
            case 125: keyboardNavigation = true; selectedIndex = movedSelection(selectedIndex, count: items.count, direction: 1); return true
            case 126: keyboardNavigation = true; selectedIndex = movedSelection(selectedIndex, count: items.count, direction: -1); return true
            case 36, 76:
                guard items.indices.contains(selectedIndex) else { return false }
                select(items[selectedIndex], false); return true
            default: return false
            }
        })
        .onChange(of: items) { _ in selectedIndex = 0 }
        .onReceive(store.$history) { history in
            if let item = previewItem, !history.items.contains(item) { previewItem = nil; searchFocused = true }
        }
        .onAppear { loginStatus = SMAppService.mainApp.status; searchFocused = true }
        .confirmationDialog("清空所有未置顶记录？", isPresented: $confirmingClear, titleVisibility: .visible) {
            Button("清空未置顶", role: .destructive) { store.clear() }
            Button("取消", role: .cancel) {}
        } message: { Text("这些记录及使用次数会从本机删除，置顶项保留。") }
        .alert("剪贴板历史", isPresented: Binding(get: { store.error != nil }, set: { if !$0 { store.error = nil } })) {
            Button("好") { store.error = nil }
        } message: { Text(store.error ?? "") }
    }

    private var header: some View {
        HStack(spacing: 10) {
            Image(systemName: "doc.on.clipboard")
                .font(.system(size: 19, weight: .medium)).foregroundStyle(HarborStyle.accent)
                .frame(width: 40, height: 40)
                .background(HarborStyle.accent.opacity(0.10), in: RoundedRectangle(cornerRadius: 12))
            VStack(alignment: .leading, spacing: 3) {
                Text("ClipHarbor").font(.system(size: 18, weight: .semibold))
                Text(store.isPaused ? "记录已暂停" : "剪贴板历史").font(.system(size: 11)).foregroundStyle(.secondary)
            }
            Spacer()
            Button { store.setPaused(!store.isPaused) } label: {
                HStack(spacing: 5) {
                    Image(systemName: store.isPaused ? "play.fill" : "pause.fill").font(.system(size: 9))
                    Text(store.isPaused ? "继续记录" : "正在记录").font(.system(size: 11, weight: .medium))
                }.padding(.horizontal, 10).padding(.vertical, 7)
                .foregroundStyle(store.isPaused ? Color.primary : HarborStyle.accent)
                .background((store.isPaused ? Color.orange : HarborStyle.accent).opacity(0.09), in: Capsule())
            }.buttonStyle(.plain)
                .help(store.isPaused ? "继续记录剪贴板" : "暂停记录剪贴板")
                .accessibilityLabel(store.isPaused ? "已暂停记录，继续记录" : "正在记录，暂停记录")
        }.padding(.horizontal, 18).padding(.top, 18).padding(.bottom, 16)
    }

    private func historyRow(_ item: Clip, index: Int) -> some View {
        let presentation = textCache.presentation(for: item)
        let pinned = store.history.pinned.contains(item)
        return HStack(spacing: 4) {
            Button { select(item, false) } label: {
                HStack(spacing: 12) {
                    Group {
                        if let data = item.imageData.first, let image = NSImage(data: data) {
